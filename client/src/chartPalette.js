// 100 цветов для диаграмм: оттенки равномерно разнесены по цветовому кругу
// «золотым углом», поэтому соседние столбики легко различить.
// Индекс = позиция значения в отсортированном по возрастанию списке голосов,
// поэтому цвета совпадают на столбиках и на круговой диаграмме.
export const CHART_COLORS = Array.from(
  { length: 100 },
  (_, i) => `hsl(${Math.round((i * 137.508) % 360)}, 65%, 50%)`,
);
